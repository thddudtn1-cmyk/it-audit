-- 증적·증빙자료. 소유 대상은 회차 점검항목·사전요청자료(F-06)·개선사항(F-07) 중 하나이며
-- 대상이 여러 종류라 (owner_type, owner_id) 로 가리킨다. 삭제는 논리 삭제만 한다.
CREATE TABLE evidence (
    evidence_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_type     VARCHAR(20)  NOT NULL,
    owner_id       BIGINT       NOT NULL,
    original_name  VARCHAR(255) NOT NULL,
    stored_path    VARCHAR(500) NOT NULL,
    file_size      BIGINT       NOT NULL,
    content_type   VARCHAR(100),
    uploaded_by    BIGINT       NOT NULL,
    uploaded_at    TIMESTAMP    NOT NULL,
    deleted_yn     CHAR(1)      DEFAULT 'N' NOT NULL,
    deleted_by     BIGINT,
    deleted_at     TIMESTAMP,
    CONSTRAINT pk_evidence PRIMARY KEY (evidence_id),
    CONSTRAINT fk_evidence_uploader FOREIGN KEY (uploaded_by) REFERENCES app_user (user_id),
    CONSTRAINT ck_evidence_owner CHECK (owner_type IN ('ROUND_ITEM', 'AUDIT_REQUEST', 'IMPROVEMENT')),
    CONSTRAINT ck_evidence_deleted CHECK (deleted_yn IN ('Y', 'N'))
);

CREATE INDEX ix_evidence_owner ON evidence (owner_type, owner_id);
