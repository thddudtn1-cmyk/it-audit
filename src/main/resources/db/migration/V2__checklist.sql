-- F-02 체크리스트 마스터 (② IT자체감사 체크리스트 1행 = 1건, 최소 단위는 '항목 상세')
-- 연도별 개정본: 적용연도(apply_year)마다 항목 집합을 따로 둔다. 순번은 연도 안에서 유일한 마스터 코드.
-- 감사 영역·감사 시기는 코드로 저장한다 (AuditArea, AuditPeriod).

CREATE TABLE checklist_item (
    item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    apply_year    INTEGER       NOT NULL,
    seq_no        INTEGER       NOT NULL,
    audit_area    VARCHAR(20)   NOT NULL,
    audit_item    VARCHAR(200)  NOT NULL,
    item_detail   VARCHAR(2000) NOT NULL,
    audit_period  VARCHAR(10)   NOT NULL,
    regulation    VARCHAR(500),
    use_yn        CHAR(1)       DEFAULT 'Y' NOT NULL,
    created_by    BIGINT,
    created_at    TIMESTAMP     NOT NULL,
    updated_by    BIGINT,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT pk_checklist_item PRIMARY KEY (item_id),
    CONSTRAINT uk_checklist_item_seq UNIQUE (apply_year, seq_no),
    CONSTRAINT ck_checklist_item_area CHECK (audit_area IN ('IT_OPS', 'SECURITY', 'DEV_CHANGE')),
    CONSTRAINT ck_checklist_item_period CHECK (audit_period IN ('Q1', 'Q2', 'Q3', 'Q4', 'EVERY')),
    CONSTRAINT ck_checklist_item_use_yn CHECK (use_yn IN ('Y', 'N'))
);

CREATE INDEX ix_checklist_item_year ON checklist_item (apply_year, audit_period);
