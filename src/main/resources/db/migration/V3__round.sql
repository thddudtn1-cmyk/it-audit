-- F-03 분기 점검 회차 (③ 분기 IT자체감사 총괄표 파일 1개 = 회차 1개, 1행 = 회차 점검항목 1건)
-- 점검결과·점검 내용 상세 등 담당자 입력 컬럼은 F-04 에서 추가한다.

CREATE TABLE audit_round (
    round_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_year   INTEGER     NOT NULL,
    quarter      INTEGER     NOT NULL,
    status       VARCHAR(20) NOT NULL,
    created_by   BIGINT,
    created_at   TIMESTAMP   NOT NULL,
    updated_by   BIGINT,
    updated_at   TIMESTAMP   NOT NULL,
    CONSTRAINT pk_audit_round PRIMARY KEY (round_id),
    CONSTRAINT uk_audit_round UNIQUE (round_year, quarter),
    CONSTRAINT ck_audit_round_quarter CHECK (quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_audit_round_status CHECK (status IN ('DRAFT', 'REVIEW', 'SUBMITTED', 'DONE'))
);

CREATE TABLE round_item (
    round_item_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id           BIGINT        NOT NULL,
    checklist_item_id  BIGINT        NOT NULL,
    team_code          VARCHAR(20),
    assignee_id        BIGINT,
    request_material   VARCHAR(1000),
    sample_size        INTEGER,
    no_reply_yn        CHAR(1)       DEFAULT 'N' NOT NULL,
    excluded_yn        CHAR(1)       DEFAULT 'N' NOT NULL,
    exclude_reason     VARCHAR(500),
    submit_status      VARCHAR(20)   DEFAULT 'NOT_SUBMITTED' NOT NULL,
    created_at         TIMESTAMP     NOT NULL,
    updated_by         BIGINT,
    updated_at         TIMESTAMP     NOT NULL,
    CONSTRAINT pk_round_item PRIMARY KEY (round_item_id),
    CONSTRAINT uk_round_item UNIQUE (round_id, checklist_item_id),
    CONSTRAINT fk_round_item_round FOREIGN KEY (round_id) REFERENCES audit_round (round_id),
    CONSTRAINT fk_round_item_checklist FOREIGN KEY (checklist_item_id) REFERENCES checklist_item (item_id),
    CONSTRAINT fk_round_item_team FOREIGN KEY (team_code) REFERENCES team (team_code),
    CONSTRAINT fk_round_item_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_round_item_sample CHECK (sample_size IS NULL OR sample_size >= 0),
    CONSTRAINT ck_round_item_no_reply CHECK (no_reply_yn IN ('Y', 'N')),
    CONSTRAINT ck_round_item_excluded CHECK (excluded_yn IN ('Y', 'N')),
    CONSTRAINT ck_round_item_exclude_reason CHECK (excluded_yn = 'N' OR exclude_reason IS NOT NULL),
    CONSTRAINT ck_round_item_submit CHECK (submit_status IN ('NOT_SUBMITTED', 'SUBMITTED', 'CONFIRMED', 'REJECTED'))
);

CREATE INDEX ix_round_item_assignee ON round_item (assignee_id);
