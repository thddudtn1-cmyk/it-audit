-- F-01 로그인·권한
-- Oracle 이전을 고려해 표준 SQL만 사용한다: 불리언은 CHAR(1) 'Y'/'N', 자동 번호는 IDENTITY 컬럼.

CREATE TABLE team (
    team_code   VARCHAR(20)  NOT NULL,
    team_name   VARCHAR(100) NOT NULL,
    sort_order  INTEGER      DEFAULT 0 NOT NULL,
    use_yn      CHAR(1)      DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT pk_team PRIMARY KEY (team_code),
    CONSTRAINT ck_team_use_yn CHECK (use_yn IN ('Y', 'N'))
);

CREATE TABLE app_user (
    user_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    login_id            VARCHAR(50)  NOT NULL,
    user_name           VARCHAR(100) NOT NULL,
    team_code           VARCHAR(20),
    role_code           VARCHAR(20)  NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    pw_change_required  CHAR(1)      DEFAULT 'N' NOT NULL,
    use_yn              CHAR(1)      DEFAULT 'Y' NOT NULL,
    last_login_at       TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uk_app_user_login_id UNIQUE (login_id),
    CONSTRAINT fk_app_user_team FOREIGN KEY (team_code) REFERENCES team (team_code),
    CONSTRAINT ck_app_user_role CHECK (role_code IN ('ADMIN', 'AUDIT_LEAD', 'INSPECTOR', 'AUDIT_DEPT', 'VIEWER')),
    CONSTRAINT ck_app_user_use_yn CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_app_user_pw_chg CHECK (pw_change_required IN ('Y', 'N'))
);

-- 감사추적: 판정·종결·파일 삭제 등 주요 행위를 남긴다 (F-11의 기반, MVP에서도 기록)
CREATE TABLE activity_log (
    log_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT,
    login_id     VARCHAR(50),
    action       VARCHAR(50)  NOT NULL,
    target_type  VARCHAR(50),
    target_id    VARCHAR(100),
    detail       VARCHAR(1000),
    client_ip    VARCHAR(50),
    created_at   TIMESTAMP    NOT NULL,
    CONSTRAINT pk_activity_log PRIMARY KEY (log_id)
);

CREATE INDEX ix_activity_log_created ON activity_log (created_at);
CREATE INDEX ix_activity_log_target ON activity_log (target_type, target_id);
