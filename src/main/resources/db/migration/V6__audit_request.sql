-- F-06 감사부서 적정성 점검: ④ 사전요청자료 1행 = 1건 (회차 점검항목당 최대 1건)
-- request_material 은 감사부서 요청자료로, ③ 사전요청자료(round_item.request_material)와 따로 저장한다 (PRD 10장).
CREATE TABLE audit_request (
    request_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_item_id     BIGINT        NOT NULL,
    request_material  VARCHAR(1000) NOT NULL,
    sample_size       INTEGER,
    remark            VARCHAR(1000),
    status            VARCHAR(20)   NOT NULL,
    dept_comment      VARCHAR(1000),
    finding_yn        CHAR(1),
    confirmed_result  VARCHAR(20),
    finding_detail    VARCHAR(2000),
    requested_by      BIGINT        NOT NULL,
    requested_at      TIMESTAMP     NOT NULL,
    submitted_by      BIGINT,
    submitted_at      TIMESTAMP,
    reviewed_by       BIGINT,
    reviewed_at       TIMESTAMP,
    updated_by        BIGINT,
    updated_at        TIMESTAMP     NOT NULL,
    CONSTRAINT pk_audit_request PRIMARY KEY (request_id),
    CONSTRAINT uk_audit_request_item UNIQUE (round_item_id),
    CONSTRAINT fk_audit_request_item FOREIGN KEY (round_item_id) REFERENCES round_item (round_item_id),
    CONSTRAINT ck_audit_request_status CHECK (status IN ('REQUESTED', 'SUBMITTED', 'REVIEWED')),
    CONSTRAINT ck_audit_request_finding CHECK (finding_yn IS NULL OR finding_yn IN ('Y', 'N')),
    CONSTRAINT ck_audit_request_result CHECK (confirmed_result IS NULL
        OR confirmed_result IN ('NEEDS_IMPROVEMENT', 'INSUFFICIENT', 'RISK')),
    CONSTRAINT ck_audit_request_sample CHECK (sample_size IS NULL OR sample_size >= 0)
);

ALTER TABLE audit_round ADD completed_by BIGINT;
ALTER TABLE audit_round ADD completed_at TIMESTAMP;
