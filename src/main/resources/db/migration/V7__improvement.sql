-- F-07 개선사항·권고사항 (⑤ 관리대장 두 시트를 한 표에 구분 컬럼으로)
-- 개선 1건이 회차 점검항목 여러 개에 걸칠 수 있어 improvement_item 으로 N:M 연결한다.
CREATE TABLE improvement (
    improvement_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind               VARCHAR(20)   NOT NULL,
    round_id           BIGINT        NOT NULL,
    team_code          VARCHAR(20),
    assignee_id        BIGINT,
    inspection_result  VARCHAR(20),
    detail             VARCHAR(4000) NOT NULL,
    improvement_plan   VARCHAR(2000),
    planned_date       DATE,
    action_result      VARCHAR(20)   NOT NULL,
    action_status      VARCHAR(2000),
    closed_yn          CHAR(1)       DEFAULT 'N' NOT NULL,
    closed_by          BIGINT,
    closed_at          TIMESTAMP,
    close_comment      VARCHAR(1000),
    created_by         BIGINT        NOT NULL,
    created_at         TIMESTAMP     NOT NULL,
    updated_by         BIGINT,
    updated_at         TIMESTAMP     NOT NULL,
    CONSTRAINT pk_improvement PRIMARY KEY (improvement_id),
    CONSTRAINT fk_improvement_round FOREIGN KEY (round_id) REFERENCES audit_round (round_id),
    CONSTRAINT fk_improvement_team FOREIGN KEY (team_code) REFERENCES team (team_code),
    CONSTRAINT fk_improvement_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_improvement_kind CHECK (kind IN ('IMPROVEMENT', 'RECOMMENDATION')),
    CONSTRAINT ck_improvement_result CHECK (inspection_result IS NULL
        OR inspection_result IN ('NORMAL', 'NEEDS_IMPROVEMENT', 'INSUFFICIENT', 'RISK')),
    CONSTRAINT ck_improvement_action CHECK (action_result IN ('PLANNED', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT ck_improvement_closed CHECK (closed_yn IN ('Y', 'N'))
);

CREATE TABLE improvement_item (
    improvement_id  BIGINT NOT NULL,
    round_item_id   BIGINT NOT NULL,
    CONSTRAINT pk_improvement_item PRIMARY KEY (improvement_id, round_item_id),
    CONSTRAINT fk_improvement_item_imp FOREIGN KEY (improvement_id) REFERENCES improvement (improvement_id),
    CONSTRAINT fk_improvement_item_ri FOREIGN KEY (round_item_id) REFERENCES round_item (round_item_id)
);

CREATE INDEX ix_improvement_open ON improvement (closed_yn, planned_date);
CREATE INDEX ix_improvement_item_ri ON improvement_item (round_item_id);
