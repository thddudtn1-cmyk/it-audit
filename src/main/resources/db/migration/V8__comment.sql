-- F-12 코멘트: 점검항목·개선사항 단위로 의견 주고받기. 삭제는 논리 삭제만 한다.
CREATE TABLE comment_note (
    comment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    target_type  VARCHAR(20)   NOT NULL,
    target_id    BIGINT        NOT NULL,
    body         VARCHAR(2000) NOT NULL,
    author_id    BIGINT        NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    deleted_yn   CHAR(1)       DEFAULT 'N' NOT NULL,
    deleted_by   BIGINT,
    deleted_at   TIMESTAMP,
    CONSTRAINT pk_comment_note PRIMARY KEY (comment_id),
    CONSTRAINT fk_comment_note_author FOREIGN KEY (author_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_comment_note_target CHECK (target_type IN ('ROUND_ITEM', 'IMPROVEMENT')),
    CONSTRAINT ck_comment_note_deleted CHECK (deleted_yn IN ('Y', 'N'))
);

CREATE INDEX ix_comment_note_target ON comment_note (target_type, target_id);
